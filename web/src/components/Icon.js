export function Icon({ name, className }) {
  const Component = icons[name] || Link2;
  return h(Component, {
    "aria-hidden": true,
    focusable: false,
    className: className || (name === "loading" ? "voice-spinner" : undefined),
    fill: name === "stop" ? "currentColor" : "none",
    strokeWidth: 1.8,
  });
}
